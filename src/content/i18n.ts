// Переклад контенту (M47). **Не локалізація**: місто, імена й деталі лишаються, адаптуються
// тільки терміни — рішення користувача 04.10.
//
// Як це влаштовано і чому саме так.
//
// Переклад живе **окремою картою «хеш джерела → англійський рядок»** (`i18n/en.json`), а не
// паралельним деревом файлів. Три причини, і всі три про те, щоб не зламати вже зроблене:
//
//   1. **Нічого не перекладається, крім того, що перекладено явно.** Рядок без запису в карті
//      лишається українським байт у байт. Ідентифікатори, ключі голосів, `focus: "50% 58%"`,
//      хендли акаунтів — усе це просто не має записів і не може змінитися. Для часткового
//      перекладу, який триватиме місяці, це єдиний безпечний режим: гра грається в будь-який день.
//   2. **Карта не ламається від правок структури.** Ключ — хеш самого тексту, не шлях і не індекс,
//      тому дописаний третій варіант відповіді чи новий епізод посеред файлу нічого не зсуває.
//   3. **Змінився оригінал — переклад відкочується сам.** Хеш більше не сходиться, рядок стає
//      українським, і це видно. Краще за тихо застарілий переклад: у проєкті без «головної мови»
//      саме це і є найчастіша помилка.
//
// Мова читається один раз при завантаженні модуля: зміна вимагає перезавантаження сторінки
// (екран вибору мови так і робить). Так увесь рушій і весь UI лишаються незмінними — вони
// отримують уже перекладений контент і про мову не знають нічого.

import enJson from './i18n/en.json';
import { readSettings } from '../telemetry/settings';

export type Lang = 'uk' | 'en';

/** FNV-1a у двох варіантах, разом 48 біт: на 12 тисячах рядків імовірність збігу ~3e-7.
 *  Короткий ключ бережe вагу: карта їде в APK, а він працює офлайн і важить скільки важить. */
export function srcHash(s: string): string {
  let a = 0x811c9dc5, b = 0x01000193;
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    a = Math.imul(a ^ c, 0x01000193) >>> 0;
    b = Math.imul(b ^ (c + i), 0x85ebca6b) >>> 0;
  }
  return (a.toString(16).padStart(8, '0') + b.toString(16).padStart(8, '0')).slice(0, 12);
}

const EN = enJson as Record<string, string>;

/** Мова пристрою, не слота: вибір один на застосунок, як розмір тексту й «менше руху». */
export const LANG: Lang = (() => {
  try { return readSettings().lang; } catch { return 'uk'; }
})();

/** Мова, якою написаний контент у `src/content/*.json` і літерали в коді. Вона не перекладається
 *  ніколи: решта мов — цілі, і додати мову означає додати файл карти й по одній гілці у функції
 *  форм **у цьому файлі**. Базова версія при цьому не змінюється — рушій і UI мов не знають. */
export const BASE_LANG: Lang = 'uk';

/** Перекласти один рядок. Немає запису — повертається оригінал, і це нормальний стан. */
export const trString = (s: string): string => (LANG === 'en' ? EN[srcHash(s)] ?? s : s);

/** Якою мовою цей рядок **зараз**. Єдине місце в проєкті, яке вміє це визначити: решта коду про
 *  мови не знає і не має знати.
 *
 *  Навіщо це взагалі. Переклад частковий і буде частковим місяцями: у збірці іншою мовою половина
 *  рядків — ще базові. Якщо в таке речення підставити ім'я, ціну або хвилину **цільовою** мовою,
 *  виходить «Their dribbler б'є з-за штрафного» — тобто переклад **змінив уже написаний текст**, а
 *  правило M47 каже, що базова версія лишається незмінною. Тому кожна вставка питає мову свого
 *  рядка-господаря і відповідає тією самою мовою. Інваріант тримає `tests/i18n.test.ts`.
 *
 *  Рядок цільовою мовою не містить письма базової — це гарантує тест «в англійських рядках немає
 *  кирилиці», тому перевірки письма достатньо і жодних позначок у контенті не потрібно. */
const BASE_SCRIPT = /[а-яіїєґА-ЯІЇЄҐ]/;
/** Рядок ще базовою мовою — тобто неперекладений. Питання «базова чи ні» не залежить від того,
 *  якою мовою зібрана гра: саме тому вставки можна перевірити тестом у будь-якій збірці.
 *
 *  Визначається письмом, і це **остаточне** рішення, а не тимчасове: правило тримається, поки
 *  базова мова — єдина кирилична з усіх, а користувач 05.10 відповів, що другої кириличної мови не
 *  буде. Якби вона колись з'явилася, точний спосіб відомий — `tr()` при завантаженні знає, які
 *  рядки створив сам, і може їх запам'ятати; але шукати це наперед не треба. */
export const isBaseText = (s: string): boolean => BASE_SCRIPT.test(s);
/** Мова рядка: базова — або мова збірки. Цим користуються `tIn`/`tfIn` і функції форм. */
export const langOf = (s: string): Lang => (isBaseText(s) ? BASE_LANG : LANG);

/** Назва клубу **окремим рядком** — заголовком екрана перед матчем, рядком стікера. Українська
 *  бере її в лапки, англійська — ні (правило «назву клубу англійською не закавучують»).
 *  Це не вирішується в карті перекладу: шаблон `«{0}»` один і той самий у заголовку клубу і в
 *  девізі голосу на титулі, а девіз лапки якраз зберігає — один рядок не може означати двох різних
 *  речей. Там, де назва стоїть усередині фрази, лапки прибирає сам переклад тієї фрази. */
export const clubTitle = (name: string): string =>
  (langOf(name) === BASE_LANG ? `«${name}»` : name);   // i18n-skip

/** Рядок, який **лягає в збереження**, а не показується одразу (мітка флага: `Mark.past`,
 *  `Mark.whenText`). У сейві має лежати базова мова, інакше перемикання мови посеред проходження
 *  лишає в кар'єрі слова попередньої — а правило каже, що кар'єра мовою не пахне. Пишеться
 *  `base('…')`: інструмент збирає такий рядок у карту так само, як `t('…')`, а перекладається він
 *  у місці показу через `tIn(langOf(…), …)`. */
export const base = (s: string): string => s;

/** `t` і `tf` мовою рядка-господаря: для базової мови повертають літерал як є, не зачіпаючи карту. */
export const tIn = (lang: Lang, s: string): string => (lang === BASE_LANG ? s : trString(s));
export function tfIn(lang: Lang, pattern: string, ...args: (string | number)[]): string {
  const p = lang === BASE_LANG ? pattern : trString(pattern);
  return p.replace(/\{(\d+)\}/g, (m, i) => String(args[Number(i)] ?? m));
}

/** Те саме для рядків, які живуть у коді, а не в контенті: ярлики кнопок, назви голосів,
 *  шматки фраз, які рушій склеює сам. Виклик у місці літерала, а не окремий файл перекладів:
 *  так літерал лишається видимим там, де він працює, і для `uk` не коштує нічого. */
export const t = trString;

/** Фраза з підстановками: `tf('тур {0} з {1}', a, b)`. Чому не склеювати перекладені шматки —
 *  порядок слів у мовах різний, і «{0} з {1}» англійською може стати «{0} of {1}» або взагалі
 *  перебудуватися. Тому в карті лежить **уся фраза з дірками**, а не окремі слова. */
export function tf(pattern: string, ...args: (string | number)[]): string {
  return trString(pattern).replace(/\{(\d+)\}/g, (m, i) => String(args[Number(i)] ?? m));
}

// ——— форми слів ————————————————————————————————————————————————————————————————
// Усе, що будує форму слова, живе тут, і тільки тут. Кожна функція має версію `…In(lang, …)` —
// нею користуються вставки в чужий рядок (див. `langOf`), — і коротку версію для мови збірки.
// Нова мова додає сюди по одній гілці і не чіпає ні рушій, ні UI.

/** Форма слова за числом. Українська має три форми («1 очко, 2 очки, 5 очок»), англійська дві,
 *  і вони не збігаються на числах, які гра реально показує: 21 очко за сезон по-українськи це
 *  `one`, а по-англійськи — «21 points». Тому для `en` беремо `one` рівно на одиниці, інакше
 *  `many`; `few` англійською просто не існує, і всі три форми перекладаються в ті самі два слова.
 *  Саме число лишається в дірці шаблону (`tf('… {0} {1}.', n, plural(n, …))`) — фразу навколо
 *  збирає шаблон, а не склейка. */
export function pluralIn(lang: Lang, n: number, one: string, few: string, many: string): string {
  if (lang === 'en') return n === 1 ? one : many;
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}
export const plural = (n: number, one: string, few: string, many: string): string =>
  pluralIn(LANG, n, one, few, many);

/** Десятковий дріб — оцінка тренера, трибун, тисячі лайків, ціна на ринку. Українська пише кому,
 *  англійська точку: у карті перекладу «7,5» лежати не може. */
export const decIn = (lang: Lang, n: number, digits = 1): string => {
  const s = n.toFixed(digits);
  return lang === 'en' ? s : s.replace('.', ',');
};
export const dec = (n: number, digits = 1): string => decIn(LANG, n, digits);

/** Порядковий номер місця, матчу, картки. Українська пише цифру з дефісом і закінченням
 *  («3-е місце», «вже 2-я жовта»), англійська — злите `st/nd/rd/th`. Закінчення передається, бо в
 *  українській воно залежить від роду слова, яке стоїть далі; англійській воно не потрібне взагалі. */
export function ordIn(lang: Lang, n: number, end = 'е' /* i18n-skip: українське закінчення */): string {
  if (lang !== 'en') return `${n}-${end}`;
  const d = n % 10, dd = n % 100;
  if (dd >= 11 && dd <= 13) return `${n}th`;
  return `${n}${d === 1 ? 'st' : d === 2 ? 'nd' : d === 3 ? 'rd' : 'th'}`;
}
export const ord = (n: number, end = 'е' /* i18n-skip: українське закінчення */): string =>
  ordIn(LANG, n, end);

/** Хвилина матчу — те саме, але з відмінком: «62-га» / «62-гу». Англійська відмінків не має,
 *  суфікс один. Стоїть тут, а не в рушії: це грамматика мови, а не правило гри. */
export function minuteOrdinalIn(lang: Lang, n: number, kase: 'nom' | 'acc' = 'nom'): string {
  const d = n % 10, dd = n % 100;
  if (lang === 'en') return ordIn(lang, n);
  let end: string;
  // Закінчення — українська граматика, не текст для гравця, тому без `t()` і з позначкою.
  if (dd >= 11 && dd <= 19) end = kase === 'nom' ? 'та' : 'ту';            // i18n-skip
  else if (n === 40) end = kase === 'nom' ? 'ва' : 'ву';                   // i18n-skip
  else if (d === 1) end = kase === 'nom' ? 'ша' : 'шу';                    // i18n-skip
  else if (d === 2) end = kase === 'nom' ? 'га' : 'гу';                    // i18n-skip
  else if (d === 3) end = kase === 'nom' ? 'тя' : 'тю';                    // i18n-skip
  else if (d === 7 || d === 8) end = kase === 'nom' ? 'ма' : 'му';         // i18n-skip
  else end = kase === 'nom' ? 'та' : 'ту';                                 // i18n-skip
  return `${n}-${end}`;
}
export const minuteOrdinal = (n: number, kase: 'nom' | 'acc' = 'nom'): string =>
  minuteOrdinalIn(LANG, n, kase);

/** Пройти структуру контенту і підмінити рядки. Форма не змінюється: ключі, числа, булеві —
 *  як були, тому типи й тести лишаються чинними. Для `uk` повертається той самий об'єкт
 *  без копіювання — нульова ціна для мови за умовчанням. */
export function tr<T>(value: T): T {
  if (LANG === 'uk') return value;
  return walk(value) as T;
}

function walk(v: unknown): unknown {
  if (typeof v === 'string') return trString(v);
  if (Array.isArray(v)) return v.map(walk);
  if (v && typeof v === 'object') {
    const out: Record<string, unknown> = {};
    for (const [k, x] of Object.entries(v as Record<string, unknown>)) out[k] = walk(x);
    return out;
  }
  return v;
}
