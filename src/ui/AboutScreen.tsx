// M26 (27.09): экран объясняет механику словами игрока — решение за матч, форма риска, складність,
// кураж, силы, неделя. **Какие именно умения качает голос — не сказано** (решение пользователя 26.09):
// игрок замечает это сам по чипам на вариантах, иначе экран превращается в таблицу характеристик.
// Процентов здесь нет по тому же правилу, что и везде.

type Props = { onBack: () => void; /** Підпис кнопки повернення: з головного меню — «Головне меню», з паузи — «Пауза». */ backLabel?: string };

export function AboutScreen({ onBack, backLabel }: Props) {
  const [feedback, setFeedback] = useState(false);
  if (feedback) return <FeedbackScreen onBack={() => setFeedback(false)} backLabel={t('Про гру')} where={t('про гру')} />;
  return (
    <div className="about plain-screen">
      <h1>{t('Про гру')}</h1>
      <p className="about-lead">{t('Гра про те, як дев’ять разів за матч не послухати себе. Один футболіст, шість голосів у голові, два кубики — і тренер із трибунами, які хочуть різного.')}</p>

      <h2>{t('Матч')}</h2>
      <ul className="about-rules">
        <li>{t('Дев’ять рішень за матч. Кожне — сцена: що відбувається зараз і три-чотири способи з цим упоратися.')}</li>
        <li>{t('Два кубики, десять граней кожен. До них додається те, що ти вмієш, і те, що зараз на полі: погода, втома, суперник, кураж.')}</li>
        <li>{t('Ісходів чотири: чисто, вийшло-але, не вийшло і катастрофа. Переграти не можна.')}</li>
      </ul>

      <h2>{t('Форма ризику й складність')}</h2>
      <ul className="about-rules">
        <li><b>{t('Упевнено')}</b> {t('— катастрофа майже неможлива, але й вирішити епізод таким рішенням зазвичай не виходить.')}</li>
        <li><b>{t('Ризиковано')}</b> {t('— так забивають. І так втрачають м’яч під контратаку.')}</li>
        <li><b>{t('Відчайдушно')}</b> {t('— рідкість: коли інші способи вже не про цей момент.')}</li>
        <li><b>{t('Форма ризику — це ціна помилки, а складність — наскільки це важко зробити.')}</b> {t('Пас назад під пресингом легкий, але небезпечний; удар із-за меж штрафного важкий, але безпечний. Майстерність звужує промах, але полосу катастрофи не викуповує.')}</li>
      </ul>

      <h2>{t('Кураж і сили')}</h2>
      <ul className="about-rules">
        <li>{t('Кураж росте від чистих ісходів на ризику — і витрачається на наступному кидку рівно на те, що дав.')}</li>
        <li>{t('Сили — ціна варіанта. Ривок і повторне зусилля коштують дорого, і до кінця матчу це відчувається.')}</li>
        <li>{t('Тренер і трибуни хочуть різного: перший дивиться на дисципліну, другі — на сміливість. Догодити обом одним рішенням не можна.')}</li>
      </ul>

      <h2>{t('Тиждень між матчами')}</h2>
      <ul className="about-rules">
        <li>{t('Між матчами — тиждень: три дні, у кожному три справи, обрати можна одну. Те, що ти обираєш, змінює наступний матч: голос гучніший, сили, спокій, довіра тренера.')}</li>
        <li>{t('У справ бувають наслідки, яких ти не замовляв, — і тоді ввечері приходить сцена. Вона теж рішення.')}</li>
      </ul>

      <h2>{t('Голоси')}</h2>
      <p className="about-lead">{t('Голос — не порада і не підказка. Це те, що Реєс хоче зробити, і кожен хоче свого. За кожним голосом стоять свої характеристики — вони на картці; що вони сильніші, то голос гучніший: спершу підказує, далі бачить те, чого інші не помітять.')}</p>
      <ul className="about-voices">
        {VOICES.map((v) => (
          <li key={v.who} className={`say voice-${v.who}`}><b>{VOICE_LABEL[v.who]}</b>{tf(' — {0} ', v.about)}<i>{tf('«{0}»', v.motto)}</i></li>
        ))}
      </ul>

      <h2>{t('Правила, яких гра дотримується')}</h2>
      <ul className="about-rules">
        <li>{t('Жодних відсотків. Форма ризику й ціль — усе, що ти знаєш до кидка.')}</li>
        <li>{t('Переграти не можна. Кубик один, і він уже впав.')}</li>
        <li>{t('Голос, якого слухаєш, стає гучнішим. Голос, якого ігноруєш, ображається.')}</li>
      </ul>

      <NoAdsCard />

      <p className="about-refs">{t('Натхнення: Disco Elysium, Football Manager і кожен матч, де ти знав, як треба, і зробив інакше.')}</p>

      <button className="row" onClick={() => setFeedback(true)}>{t('Написати розробнику')}</button>
      {reviewAvailable() && <button className="row" onClick={() => openStorePage('about')}>{t('Оцінити гру в Google Play')}</button>}
      <button className="row row-back" onClick={onBack}>{backLabel ?? t('Головне меню')}</button>
      <p className="build">{buildLabel()}</p>
    </div>
  );
}
