// Краї плівки (19.09 титул; 20.09 — на всіх екранах гри, решение пользователя): дві вузькі перфоровані
// смуги по краях вікна, фіксовані, під контентом. Ширина 10 px — рівно зазор між листом/зошитом і краєм
// (#root 16 px мінус виступ 6 px), тому смуги нічого не перекривають і на телефоні. Підписи (кадр
// «01A02», назва, слот) — тільки на титулі; у матчі й на решті екранів — лише перфорація: у смузі 10 px
// текст читається на межі, а в матчі він змагався б із хвилиною і рахунком. Немає на дошці аналітика,
// у стрічці «Y» і на сторінці ESPM — це навмисно «чужі» екрани, рамка кадру ламала б імітацію.

type Props = { labels?: { left: string[]; right: string[] } };

export function Film({ labels }: Props) {
  return (
    <>
      <aside className="film film-left" aria-hidden="true">{labels?.left.map((t, i) => <span key={i}>{t}</span>)}</aside>
      <aside className="film film-right" aria-hidden="true">{labels?.right.map((t, i) => <span key={i}>{t}</span>)}</aside>
    </>
  );
}
