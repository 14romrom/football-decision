// Перехід між екранами (16.10): за матч гравець проходить вісім екранів — лист, кидок, стрічку,
// свисток, дошку, дельту, ESPM, «Y», тиждень — і кожен досі з'являвся обривом.
//
// Чому заслінкою, а не прозорістю самого екрана. Анімувати `opacity` контейнера з грою не можна:
// всередині нього лежать `position: fixed` смуги плівки і прилиплі кнопки, а елемент із
// `opacity < 1` стає для них точкою відліку — на час переходу вони б стрибали. Тому зверху лягає
// окремий аркуш кольору фону і гасне: розкладки він не чіпає взагалі, а читається тим самим
// розчиненням, що й на екрані запуску.
//
// `key` на тригері змушує React замінити вузол, тож анімація грає заново на кожну зміну екрана.
// «Менше руху» прибирає її в CSS.

type Props = {
  /** Що вважати зміною екрана: маршрут в App, `stage.k` у матчі. */
  on: string;
};

export function ScreenWipe({ on }: Props) {
  return <div key={on} className="screen-wipe" aria-hidden="true" />;
}
