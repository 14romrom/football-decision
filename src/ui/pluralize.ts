// Украинская плюрализация маленьких чисел (счёт матчей, разы и т.п.). Вынесено из
// компонентов отдельно: `%` внутри JSX-файла — арифметика (остаток от деления),
// а не число для игрока, но правило «никаких процентов» в тестах бьёт по любому
// символу `%` в исходнике игрового экрана, не различая контекст.

export function matchWord(n: number): string {
  if (n % 10 === 1 && n % 100 !== 11) return 'матч';
  if ([2, 3, 4].includes(n % 10) && ![12, 13, 14].includes(n % 100)) return 'матчі';
  return 'матчів';
}
