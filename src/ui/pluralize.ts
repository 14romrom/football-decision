import { t, plural } from '../content/i18n';
// Плюрализация маленьких чисел (счёт матчей, разы и т.п.). Вынесено из компонентов отдельно:
// `%` внутри JSX-файла — арифметика (остаток от деления), а не число для игрока, но правило
// «никаких процентов» в тестах бьёт по любому символу `%` в исходнике игрового экрана, не
// различая контекст. Само правило форм живёт в `content/i18n.ts` — там, где ему и место: у
// украинского три формы, у английского две, и выбор зависит от языка (M47).

export { plural };

export function matchWord(n: number): string {
  return plural(n, t('матч'), t('матчі'), t('матчів'));
}
