// Картка, якої в ісході немає (ревʼю 24.10). Текст згадує жовту й червону не лише тоді, коли суддя її показує:
// «жовтої нема», «без червоної» — заперечення; «з жовтою», «вже мав жовту», «жовта в тебе вже є» — стара
// картка, з якою граєш далі; «наступне слово — жовта» — погроза; «з червоним обличчям» — не картка взагалі.
// Поле на кожну таку згадку діставало картку. Маска замінює ці звороти пробілами тієї ж довжини, тож позиція
// решти тексту (за нею кінцівки стають у порядок) не зсувається. Спільна для action-ends і anim-coverage.
const NO_CARD = /без картк\S*|картки не\S*|не дає картк\S*|не показує картк\S*|жовтої (немає|нема)|без червоної|(з|із) жовтою|(з|із) карткою|червоним обличчям|(вже|уже) мав жовту|жовта в тебе вже є|наступне слово — жовта/g;

export const maskNoCard = (s: string): string => s.replace(NO_CARD, (m) => ' '.repeat(m.length));
